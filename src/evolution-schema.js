export const EVOLUTION_SCHEMA = `
CREATE TABLE IF NOT EXISTS evo_suites(scope TEXT NOT NULL,id TEXT NOT NULL,contract TEXT NOT NULL,hash TEXT NOT NULL,
  created INTEGER NOT NULL,last_started INTEGER,PRIMARY KEY(scope,id));
CREATE TABLE IF NOT EXISTS evo_runs(id TEXT PRIMARY KEY,scope TEXT NOT NULL,suite TEXT NOT NULL,suite_hash TEXT NOT NULL,
  owner TEXT NOT NULL,session TEXT NOT NULL,state TEXT NOT NULL,phase TEXT NOT NULL,created INTEGER NOT NULL,
  finished INTEGER,lease INTEGER NOT NULL,epoch INTEGER NOT NULL,round INTEGER NOT NULL DEFAULT 0,
  reason TEXT,memory TEXT REFERENCES memories(id) ON DELETE SET NULL,summary TEXT);
CREATE INDEX IF NOT EXISTS evo_run_scope ON evo_runs(scope,created);
CREATE TABLE IF NOT EXISTS evo_calls(id TEXT PRIMARY KEY,run TEXT NOT NULL REFERENCES evo_runs(id) ON DELETE CASCADE,
  day TEXT NOT NULL,phase TEXT NOT NULL,created INTEGER NOT NULL,outcome TEXT NOT NULL,usage TEXT);
CREATE INDEX IF NOT EXISTS evo_call_day ON evo_calls(day);
CREATE INDEX IF NOT EXISTS evo_call_run ON evo_calls(run);
CREATE TABLE IF NOT EXISTS evo_request_sizes(call TEXT PRIMARY KEY REFERENCES evo_calls(id) ON DELETE CASCADE,bytes INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS evo_dependencies(run TEXT NOT NULL REFERENCES evo_runs(id) ON DELETE CASCADE,
  memory TEXT NOT NULL REFERENCES memories(id) ON DELETE CASCADE,PRIMARY KEY(run,memory));
CREATE TABLE IF NOT EXISTS evo_probes(id TEXT PRIMARY KEY,run TEXT NOT NULL REFERENCES evo_runs(id) ON DELETE CASCADE,
  label TEXT NOT NULL,split TEXT NOT NULL,strategy TEXT NOT NULL,results TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS evo_versions(memory TEXT PRIMARY KEY REFERENCES memories(id) ON DELETE CASCADE,
  scope TEXT NOT NULL,suite TEXT NOT NULL,suite_hash TEXT NOT NULL,run TEXT NOT NULL REFERENCES evo_runs(id),
  parent TEXT REFERENCES memories(id) ON DELETE SET NULL,state TEXT NOT NULL,created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS evo_version_suite ON evo_versions(scope,suite,created);
`
